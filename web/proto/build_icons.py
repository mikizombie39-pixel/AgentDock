"""Build web/proto/icons.js: the Lucide icons used by the dialogue prototype, as data URIs.

The prototype is opened as a local file (the server serves only web/*), so icons are embedded.
Lucide is ISC-licensed (see ICONS-LICENSE.txt); the licence text ships next to the generated file.
Usage: python build_icons.py [path to lucide-static/icons]
"""
import base64
import sys
from pathlib import Path

SRC = Path(sys.argv[1] if len(sys.argv) > 1 else "C:/Users/mikiz/AgentDock-local/tmp/lucide/package/icons")
OUT = Path(__file__).with_name("icons.js")

# key: (lucide name, colour). Colour carries the party: AI teal, the person brown, supermarket blue, ryotei vermilion.
ICONS = {
    "ai": ("bot", "#1D6670"),
    "human": ("user-round", "#8A5A12"),
    "super": ("shopping-cart", "#2F5D8A"),
    "ryotei": ("hand-platter", "#A4372A"),
    "buri": ("fish", "#27221D"),
    "shiro": ("shrimp", "#B0563C"),
    "coop": ("ship", "#27221D"),
    "csha": ("package", "#27221D"),
    "bid": ("gavel", "#27221D"),
    "deal": ("handshake", "#27221D"),
    "stamp": ("stamp", "#8A5A12"),
    "reg": ("receipt-japanese-yen", "#2E6B4F"),
    "shield": ("shield-check", "#2E6B4F"),
    "memo": ("notebook-text", "#27221D"),
    "hand": ("pointer", "#27221D"),
    "slip": ("clipboard-list", "#8A5A12"),
}


def main() -> int:
    lines = ["// Generated by build_icons.py from Lucide (https://lucide.dev, ISC licence, see ICONS-LICENSE.txt). Do not edit by hand.",
             "window.ICONS = {"]
    for key, (name, colour) in ICONS.items():
        f = SRC / f"{name}.svg"
        if not f.exists():
            print(f"missing: {f}", file=sys.stderr)
            return 1
        svg = f.read_bytes().decode("utf-8")
        svg = svg.replace('stroke="currentColor"', f'stroke="{colour}"').replace('stroke-width="2"', 'stroke-width="1.75"')
        if f'stroke="{colour}"' not in svg:
            print(f"no stroke to colour in {name}", file=sys.stderr)
            return 1
        data = base64.b64encode(svg.encode("utf-8")).decode("ascii")
        lines.append(f'  {key}: "data:image/svg+xml;base64,{data}",')
    lines.append("};")
    OUT.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    print(f"wrote {OUT} ({OUT.stat().st_size:,} bytes, {len(ICONS)} icons)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
